def _save_share(share_id, title, messages, created_at):
    con = _sqlite3.connect(_SHARES_DB)
    con.execute("INSERT OR REPLACE INTO shares VALUES (?,?,?,?)",
                (share_id, title, json.dumps(messages), created_at))
    con.commit()
    con.close()

def _load_share(share_id):
    con = _sqlite3.connect(_SHARES_DB)
    row = con.execute("SELECT title, messages, created_at FROM shares WHERE share_id=?",
                      (share_id,)).fetchone()
    con.close()
    if not row:
        return None
    return {"title": row[0], "messages": json.loads(row[1]), "created_at": row[2]}

