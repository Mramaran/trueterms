class RunContractRequest(BaseModel):
    contract: dict

@app.post("/run-contract", dependencies=[Depends(verify_api_key)])
async def run_contract(req: RunContractRequest):  # VERSION-2
    print("[V2] run_contract called")
    """
    Forward the ACTUS contract payload to the live ACTUS server and return cash flow events.
    """
    actus_url = f"{ACTUS_SERVER_URL}/eventsBatch"
    try:
        # ACTUS server expects: { contracts: [...], riskFactors: [] }
        # Frontend sends: { contract: { contracts: [...], riskFactors: [] } }
        # So req.contract IS the full payload already
        inner = req.contract
        if "contracts" in inner:
            # Already correct format: { contracts: [...], riskFactors: [] }
            payload = inner
        else:
            # Raw contract fields — wrap them
            payload = {"contracts": [inner], "riskFactors": inner.pop("riskFactors", [])}
        print(f"[RUN-CONTRACT] Final payload keys: {list(payload.keys())}, contracts count: {len(payload.get('contracts', []))}")
        print(f"[RUN-CONTRACT] Contract fields: {list(payload['contracts'][0].keys()) if payload.get('contracts') else 'none'}")

        print(f"[RUN-CONTRACT] Sending payload: {json.dumps(payload)[:600]}")
        # Retry up to 3 times — ACTUS server is occasionally flaky
        last_error = None
        resp = None
        for attempt in range(1, 4):
            try:
                async with httpx.AsyncClient(timeout=30.0) as client:
                    resp = await client.post(
                        actus_url,
                        json=payload,
                        headers={"Content-Type": "application/json"},
                    )
                if resp.status_code == 200:
                    print(f"[RUN-CONTRACT] Success on attempt {attempt}")
                    break
                else:
                    last_error = f"ACTUS server returned {resp.status_code}: {resp.text[:200]}"
                    print(f"[RUN-CONTRACT] Attempt {attempt} failed: {last_error}")
            except Exception as e:
                last_error = str(e)
                print(f"[RUN-CONTRACT] Attempt {attempt} exception: {last_error}")
                resp = None
            if attempt < 3:
                import asyncio
                await asyncio.sleep(2)
        if resp is None or resp.status_code != 200:
            raise HTTPException(status_code=502, detail=f"ACTUS server unavailable after 3 attempts: {last_error}")
        data = resp.json()
        # ACTUS returns a list of result objects, each with an 'events' key
        # Flatten events for easy frontend consumption
        events = []
        if isinstance(data, list):
            for item in data:
                if isinstance(item, dict) and 'events' in item:
                    events.extend(item['events'])
                elif isinstance(item, list):
                    events.extend(item)
        # Write full response to log file for debugging
        log_path = PROJECT_ROOT / "actus_debug.json"
        with open(log_path, 'w') as f:
            json.dump({"payload": payload, "response": data}, f, indent=2)
        print(f"[RUN-CONTRACT] Full debug written to actus_debug.json")
        print(f"[RUN-CONTRACT] Raw ACTUS response: {json.dumps(data)[:500]}")
        print(f"[RUN-CONTRACT] ACTUS server response: {len(data)} result(s), {len(events)} events")
        print(f"[RUN-CONTRACT] Sample event: {events[0] if events else 'none'}")
        return {"success": True, "results": data, "events": events}
    except httpx.TimeoutException:
        raise HTTPException(status_code=504, detail="ACTUS server timed out (30s). Check connectivity.")
    except HTTPException:
        raise
    except Exception as e:
        import traceback
        print(f"[RUN-CONTRACT ERROR] {e}\n{traceback.format_exc()}")
        raise HTTPException(status_code=500, detail=f"ACTUS run failed: {str(e)}")


