class XBRLParseResponse(BaseModel):
    success: bool
    filename: str
    standard_detected: str
    instruments_found: int
    confidence: int
    warnings: list
    suggested_contracts: list
    raw_fields_count: int
    ready_to_run: bool
    payload: Optional[dict] = None


@app.post("/parse-xbrl", response_model=XBRLParseResponse, dependencies=[Depends(verify_api_key)])
async def parse_xbrl_file(file: UploadFile = File(...)):
    """
    Accept an XBRL / XML financial report file and extract ACTUS contract fields.
    Supports: IFRS XBRL, US-GAAP XBRL, Generic financial XML.
    Returns a structured response with suggested ACTUS contract payload.
    """
    # ── Validate file extension ────────────────────────────────────────────
    allowed_xbrl_exts = {'.xml', '.xbrl', '.xsd', '.htm', '.html'}
    import os as _os
    ext = _os.path.splitext(file.filename or '')[1].lower()
    if ext not in allowed_xbrl_exts:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type '{ext}'. Allowed: {', '.join(allowed_xbrl_exts)}"
        )

    # ── Read file content ──────────────────────────────────────────────────
    try:
        raw_bytes = await file.read()
        if not raw_bytes:
            raise HTTPException(status_code=400, detail="Empty file uploaded.")
        if len(raw_bytes) > MAX_FILE_SIZE_BYTES:
            raise HTTPException(
                status_code=413,
                detail=f"File too large ({round(len(raw_bytes)/1024/1024, 1)} MB). Max 50 MB."
            )
        file_content = raw_bytes.decode('utf-8', errors='replace')
        # iXBRL slicing is handled inside xbrl_parser._ixbrl_to_xbrl_xml()
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not read uploaded file: {str(e)}")

    # ── Detect XBRL standard from content ─────────────────────────────────
    standard_detected = "Generic Financial XML"
    if 'ifrs' in file_content.lower() or 'xbrl.ifrs.org' in file_content:
        standard_detected = "IFRS XBRL"
    elif 'us-gaap' in file_content.lower() or 'fasb.org' in file_content:
        standard_detected = "US-GAAP XBRL"
    elif 'rbi' in file_content.lower() or 'in-bfsi' in file_content.lower():
        standard_detected = "RBI / India XBRL (IFRS-aligned)"

    # ── Run the XBRL parser ────────────────────────────────────────────────
    try:
        result = parse_xbrl(file_content)
    except Exception as e:
        import traceback
        print(f"[PARSE-XBRL ERROR] {e}\n{traceback.format_exc()}")
        raise HTTPException(status_code=500, detail=f"XBRL parsing failed: {str(e)}")

    if not result.get('success'):
        raise HTTPException(
            status_code=422,
            detail=result.get('error', 'XBRL parsing failed — invalid XML structure.')
        )

    # ── Build response ─────────────────────────────────────────────────────
    suggested = result.get('suggested_contracts', [])
    confidence = suggested[0]['confidence'] if suggested else 0
    payload    = suggested[0]['payload']    if suggested else None
    ready      = confidence >= 60 and payload is not None

    print(
        f"[PARSE-XBRL] '{file.filename}' | Standard: {standard_detected} | "
        f"Instruments: {len(result.get('instruments', []))} | "
        f"Confidence: {confidence}% | Ready: {ready}"
    )

    return XBRLParseResponse(
        success=True,
        filename=file.filename or 'unknown',
        standard_detected=standard_detected,
        instruments_found=len(result.get('instruments', [])),
        confidence=confidence,
        warnings=result.get('warnings', []),
        suggested_contracts=suggested,
        raw_fields_count=len(result.get('raw_fields', {})),
        ready_to_run=ready,
        payload=payload,
    )


