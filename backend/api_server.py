@app.post("/voice-contract", dependencies=[Depends(verify_api_key)])
async def voice_contract(req: VoiceContractRequest):
    """
    Parse a voice transcript into an ACTUS contract JSON using Claude.
    Returns { detected: bool, contract: {...} | null, params: {...} }
    """
    transcript = req.transcript.strip()
    if not transcript:
        raise HTTPException(status_code=400, detail="Empty transcript")

    from datetime import datetime
    today = datetime.now()

    prompt = f"""You are an ACTUS financial contract parameter extractor.

Voice command: "{transcript}"

ACTUS contract types:
  PAM = Principal at Maturity, ANN = Annuity, LAM = Linear Amortizer,
  NAM = Negative Amortizer, CLM = Call Money, STK = Stock,
  COM = Commodity, CSH = Cash

Extract and return ONLY a JSON object with exactly these fields:
{{
  "detected": true or false,
  "contractType": "PAM" | "ANN" | "LAM" | "NAM" | "CLM" | "STK" | "COM" | "CSH" | null,
  "notionalPrincipal": number or null,
  "currency": "USD" | "EUR" | "GBP" | "JPY" | "CHF" | null,
  "nominalInterestRate": decimal (0.05 for 5%) or null,
  "maturityYears": integer or null
}}

Rules:
- "detected" is true ONLY when a clear contract generation intent is present
  (e.g. words like generate, create, make, build, PAM contract, annuity, etc.)
- Default currency to "USD" if amount mentioned without currency symbol
- Convert: "5%" or "5 percent" → 0.05
- Return ONLY valid JSON, absolutely no text outside the JSON object"""

    try:
        client = get_client()
        response = client.chat.completions.create(
            model=LLM_MODEL,
            messages=[{"role": "user", "content": prompt}],
            response_format={"type": "json_object"}
        )
        import json as _json
        params = _json.loads(response.choices[0].message.content)

        if not params.get("detected"):
            return {"detected": False, "contract": None, "params": params}

        ct        = (params.get("contractType") or "PAM").upper()
        notional  = float(params.get("notionalPrincipal") or 1000)
        rate      = float(params.get("nominalInterestRate") or 0.05)
        currency  = params.get("currency") or "USD"
        years     = int(params.get("maturityYears") or 5)

        status_date   = today.strftime("%Y-%m-%dT00:00:00")
        maturity_date = f"{today.year + years}-{today.month:02d}-{today.day:02d}T00:00:00"

        contract = {
            "contractType": ct,
            "contractID":   f"VOICE-{today.strftime('%Y%m%d%H%M%S')}",
            "statusDate":               status_date,
            "initialExchangeDate":      status_date,
            "maturityDate":             maturity_date,
            "notionalPrincipal":        notional,
            "nominalInterestRate":      rate,
            "currency":                 currency,
            "dayCountConvention":       "A365",
            "cycleOfInterestPayment":   "P1YL1",
            "cycleAnchorDateOfInterestPayment": status_date,
        }

        print(f"[VOICE-CONTRACT] {ct} | {notional} {currency} | {rate*100:.1f}% | {years}yr → {maturity_date}")
        return {"detected": True, "contract": contract, "params": params}

    except Exception as e:
        import traceback
        print(f"[VOICE-CONTRACT ERROR] {e}\n{traceback.format_exc()}")
        raise HTTPException(status_code=500, detail=f"Contract parsing failed: {str(e)}")


@app.post("/run-contract", dependencies=[Depends(verify_api_key)])
async def run_contract(request: Request):
    body = await request.json()
    # body is { contract: { contracts: [...], riskFactors: [] } }
    inner = body.get('contract', body) if isinstance(body, dict) else body
    if isinstance(inner, dict) and 'contracts' in inner:
        actus_payload = inner  # already { contracts: [...], riskFactors: [] }
    elif isinstance(inner, list):
        actus_payload = {"contracts": inner, "riskFactors": []}
    else:
        actus_payload = {"contracts": [inner], "riskFactors": []}

    print(f"[RUN-CONTRACT-V3] Sending to ACTUS: {str(actus_payload)[:200]}")
    try:
        async with httpx.AsyncClient(verify=False, timeout=30.0) as client:
            res = await client.post(
                f"{ACTUS_SERVER_URL}/eventsBatch",
                json=actus_payload,
                headers={"Content-Type": "application/json"},
            )
            res.raise_for_status()
            data = res.json()
            # ACTUS returns: [{ contractID, status, events: [...] }]
            # Extract all events into flat list
            events = []
            for item in (data if isinstance(data, list) else [data]):
                if isinstance(item, dict) and 'events' in item:
                    events.extend(item['events'])
            print(f"[RUN-CONTRACT-V3] Got {len(events)} events from ACTUS")
            return {"success": True, "results": data, "events": events}
    except Exception as e:
        print(f"[RUN-CONTRACT-V3] Error: {str(e)}")
        raise HTTPException(status_code=502, detail=f"Could not reach ACTUS server: {str(e)}")


@app.post("/read-file", dependencies=[Depends(verify_api_key)])
def read_file(req: FileReadRequest):
    path = Path(req.path.strip())
    if not path.exists():
        raise HTTPException(status_code=404, detail=f"Path not found: {path}")

    if path.is_dir():
        SKIP_DIRS = {'.git', '__pycache__', 'node_modules', 'env', '.venv',
                     'chroma_db', 'db', 'dist', 'build', '.next', '.cache'}

        def collect_files(folder: Path, prefix: str = "") -> list:
            result = []
            try:
                for entry in sorted(folder.iterdir()):
                    if entry.is_dir():
                        skipped = entry.name in SKIP_DIRS
                        result.append({"name": f"{prefix}{entry.name}/", "type": "folder",
                                       "skipped": skipped, "path": str(entry)})
                        if not skipped:
                            result.extend(collect_files(entry, prefix + entry.name + "/"))
                    else:
                        result.append({
                            "name": f"{prefix}{entry.name}", "type": "file",
                            "size_bytes": entry.stat().st_size,
                            "extension": entry.suffix.lower(),
                            "path": str(entry), "skipped": False,
                        })
            except PermissionError:
                pass
            return result

        all_entries = collect_files(path)
        files = [e for e in all_entries if e['type'] == 'file']
        lines = [f"Folder: {path}", f"Total: {len(files)} files", "", "📁 Structure:"]
        for e in all_entries:
            if e['type'] == 'folder':
                lines.append(f"  📁 {e['name']}{' (skipped)' if e['skipped'] else ''}")
            else:
                lines.append(f"  📄 {e['name']} ({round(e.get('size_bytes',0)/1024,1)} KB)")
        lines += ["", "📄 File Contents:", "=" * 60]

        total_chars = 0
        for f in files:
            if total_chars >= 300_000:
                lines.append("\n... [content limit reached]")
                break
            fpath = Path(f['path'])
            lines.append(f"\n### {f['name']}")
            if f['extension'] in ALLOWED_EXTENSIONS:
                try:
                    text = fpath.read_text(encoding='utf-8', errors='replace')
                    flines = text.splitlines()
                    if len(flines) > 500:
                        text = '\n'.join(flines[:500]) + "\n... [truncated]"
                    lines.append(text)
                    total_chars += len(text)
                except Exception:
                    lines.append("[Could not read]")
            else:
                lines.append("[Binary/unsupported]")
            lines.append("-" * 60)

        return {"path": str(path), "filename": path.name, "size_bytes": 0,
                "extension": "", "content": "\n".join(lines),
                "lines": len(all_entries), "is_directory": True, "entries": all_entries}

    if path.suffix.lower() not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail=f"File type '{path.suffix}' not allowed.")
    size = path.stat().st_size
    if size > MAX_FILE_SIZE_BYTES:
        raise HTTPException(status_code=413, detail=f"File too large ({round(size/1024/1024,1)} MB).")
    try:
        content = path.read_text(encoding='utf-8', errors='replace')
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not read file: {str(e)}")
    return {"path": str(path), "filename": path.name, "size_bytes": size,
            "extension": path.suffix, "content": content,
            "lines": content.count('\n') + 1, "is_directory": False}


@app.post("/write-file", dependencies=[Depends(verify_api_key)])
def write_file(req: FileWriteRequest):
    path = Path(req.path.strip())
    if path.suffix.lower() not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail=f"File type '{path.suffix}' not allowed.")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        if req.mode == "append":
            with open(path, 'a', encoding='utf-8') as f:
                f.write(req.content)
            action = "appended"
        elif req.mode == "create_new":
            if path.exists():
                raise HTTPException(status_code=409, detail=f"File already exists: {path}")
            path.write_text(req.content, encoding='utf-8')
            action = "created"
        else:
            path.write_text(req.content, encoding='utf-8')
            action = "overwritten"
        return {"path": str(path), "filename": path.name, "action": action,
                "size_bytes": path.stat().st_size,
                "lines": req.content.count('\n') + 1, "success": True}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not write file: {str(e)}")


