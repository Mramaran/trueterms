# ── Explicit language request detection ──────────────────────────────────────
# Maps phrases the user might say → language name to respond in
_EXPLICIT_LANG_PATTERNS = [
    (r'\bin (english|english language)\b',                          'English'),
    (r'\b(give|answer|respond|reply|explain|tell me)\s+(in|using)\s+english\b', 'English'),
    (r'\bin (tamil|tamil language)\b',                              'Tamil'),
    (r'\b(give|answer|respond|reply|explain|tell me)\s+(in|using)\s+tamil\b',  'Tamil'),
    (r'தமிழில்|தமிழ்ல',                                             'Tamil'),
    (r'\bin (hindi|hindi language)\b',                              'Hindi'),
    (r'\b(give|answer|respond|reply|explain|tell me)\s+(in|using)\s+hindi\b',  'Hindi'),
    (r'हिंदी में|हिन्दी में',                                         'Hindi'),
    (r'\bin (french|français|francais)\b',                          'French'),
    (r'en français|en francais',                                    'French'),
    (r'\bin (german|deutsch)\b',                                    'German'),
    (r'auf deutsch',                                                'German'),
    (r'\bin (spanish|español|espanol)\b',                           'Spanish'),
    (r'en español|en espanol',                                      'Spanish'),
    (r'\bin (portuguese|português|portugues)\b',                    'Portuguese'),
    (r'\bin (japanese|日本語)\b',                                    'Japanese'),
    (r'\bin (korean|한국어)\b',                                      'Korean'),
    (r'\bin (italian|italiano)\b',                                  'Italian'),
    (r'\bin (indonesian|bahasa indonesia)\b',                       'Indonesian'),
]

def detect_explicit_language(query: str) -> str | None:
    """Return the explicitly requested language name, or None if not found."""
    lower = query.lower()
    for pattern, lang_name in _EXPLICIT_LANG_PATTERNS:
        if re.search(pattern, lower if pattern.isascii() else query, re.IGNORECASE):
            return lang_name
    return None

def get_language_instruction(lang_code: str, query: str = '') -> str:
    """Build the language instruction, honouring explicit user requests first."""
    # Priority 1 — explicit request in the message
    explicit = detect_explicit_language(query)
    if explicit:
        if explicit == 'English':
            return ''   # English needs no special instruction
        return (
            f'IMPORTANT: The user has explicitly requested a response in {explicit}. '
            f'You MUST respond in {explicit} regardless of any other language setting. '
            f'Only keep technical terms, JSON field names, and code in English.'
        )
    # Priority 2 — UI language setting
    if not lang_code or lang_code in ('en', 'tanglish'):
        return ''
    lang_name = LANGUAGE_NAMES.get(lang_code, lang_code)
    return (
        f'IMPORTANT: You must respond in {lang_name}. '
        f'All your text, explanations, and descriptions must be in {lang_name}. '
        f'Only keep technical terms, JSON field names, and code in English.'
    )

