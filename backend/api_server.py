# Lazy-load the model once and keep it in memory.
_whisper_model = None
_whisper_lock  = threading.Lock()

def _get_whisper():
    global _whisper_model
    if _whisper_model is not None:
        return _whisper_model
    with _whisper_lock:
        if _whisper_model is None:
            try:
                import whisper
                print("[WHISPER] Loading 'small' model (English)…")
                _whisper_model = whisper.load_model("small")
                print("[WHISPER] Model ready.")
            except ImportError:
                raise HTTPException(
                    status_code=501,
                    detail="openai-whisper not installed. Run: pip install openai-whisper"
                )
    return _whisper_model


WHISPER_LANGUAGES = {"en": "en", "ta": "ta", "hi": "hi", "auto": None}  # None = Whisper auto-detect

@app.post("/transcribe")
async def transcribe(audio: UploadFile = File(...), language: Optional[str] = Form("en")):
    """
    Accepts a raw audio file (webm/ogg/wav/mp4) from the browser's
    MediaRecorder, transcribes it with Whisper, and returns { transcript: str }.
    Optional form field `language`: 'en' (default) | 'ta' | 'hi' | 'auto'.
    """
    lang = (language or "en").strip().lower()
    if lang not in WHISPER_LANGUAGES:
        lang = "en"
    # Persist audio to a temp file so Whisper can decode it
    suffix = ".webm"
    if audio.content_type:
        ct = audio.content_type.lower()
        if "ogg" in ct:   suffix = ".ogg"
        elif "wav" in ct:  suffix = ".wav"
        elif "mp4" in ct or "mpeg" in ct: suffix = ".mp4"
        # webm with codecs annotation (e.g. audio/webm;codecs=opus) — keep .webm
        elif "webm" in ct: suffix = ".webm"

    try:
        raw = await audio.read()
        if not raw:
            raise HTTPException(status_code=400, detail="Empty audio file")

        with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as tmp:
            tmp.write(raw)
            tmp_path = tmp.name

        # ACTUS domain vocabulary — teaches Whisper to recognise these terms correctly
        ACTUS_PROMPT = (
            "ACTUS financial contract. Contract types: PAM, ANN, LAM, NAM, CLM, STK, COM, CSH. "
            "Fields: notionalPrincipal, nominalInterestRate, maturityDate, riskFactors, "
            "cycleOfInterestPayment, cycleOfRateReset, rateSpread, marketObjectCode, "
            "dayCountConvention, contractRole, contractID, statusDate, "
            "initialExchangeDate, cycleOfPrincipalRedemption. "
            "Units: USD, EUR, GBP, basis points, bps, percent, LIBOR, US Treasury, SOFR. "
            "Generate a PAM contract for a loan of USD 10000 for 5 years "
            "at an interest rate of 5 percent and a US Treasury risk factor rate of 1 percent."
        )
        model = _get_whisper()
        # fp16=False avoids CUDA errors on CPU; language=None lets Whisper auto-detect
        result = model.transcribe(
            tmp_path,
            language=WHISPER_LANGUAGES[lang],
            fp16=False,
            temperature=0.0,          # deterministic
            # English ACTUS vocabulary prompt only for English; it would bias ta/hi/auto
            initial_prompt=ACTUS_PROMPT if lang == "en" else None,
            condition_on_previous_text=True,
            no_speech_threshold=0.6,
            compression_ratio_threshold=2.4,
            beam_size=5,              # better accuracy (was 1)
            best_of=5,                # pick best of 5 candidates
        )
        transcript = result.get("text", "").strip()
        print(f"[WHISPER] ({lang}) Transcript: {transcript!r}")
        return {"transcript": transcript}

    except HTTPException:
        raise
    except Exception as e:
        import traceback
        print(f"[WHISPER ERROR] {e}\n{traceback.format_exc()}")
        raise HTTPException(status_code=500, detail=f"Transcription failed: {str(e)}")
    finally:
        try:
            import os as _os
            _os.unlink(tmp_path)
        except Exception:
            pass


